/**
 * Generate src/spdxData.ts (spec 024): the SPDX license and exception ids that
 * `registerPlugin` validates a plugin's `licence` against, embedded so the
 * check runs offline. Sources: `spdx-license-ids` (CC0-1.0; current and
 * deprecated ids) and `spdx-exceptions` (CC-BY-3.0), both build-time
 * devDependencies; attribution is in NOTICE.
 *
 *   npx tsx scripts/generate-spdx.ts          # write src/spdxData.ts
 *   npx tsx scripts/generate-spdx.ts --check  # exit 1 when it is stale
 */
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { createRequire } from "node:module";

const require_ = createRequire(import.meta.url);
const OUT_FILE = path.join(path.dirname(url.fileURLToPath(import.meta.url)), "..", "src", "spdxData.ts");

function serialise(): string {
  const ids = [...new Set([...require_("spdx-license-ids"), ...require_("spdx-license-ids/deprecated.json")] as string[])].sort();
  const exceptions = [...(require_("spdx-exceptions") as string[])].sort();
  const idsVersion = require_("spdx-license-ids/package.json").version;
  const exVersion = require_("spdx-exceptions/package.json").version;
  return [
    "// Generated by scripts/generate-spdx.ts — do not edit.",
    `// From spdx-license-ids ${idsVersion} (CC0-1.0) and spdx-exceptions ${exVersion} (CC-BY-3.0, attribution in NOTICE).`,
    "",
    "/** SPDX license ids, current and deprecated. */",
    `export const SPDX_LICENSE_IDS: readonly string[] = ${JSON.stringify(ids)};`,
    "",
    "/** SPDX license exception ids (after WITH). */",
    `export const SPDX_EXCEPTION_IDS: readonly string[] = ${JSON.stringify(exceptions)};`,
    "",
  ].join("\n");
}

/** True when src/spdxData.ts matches the installed packages. */
export function checkSpdxData(): boolean {
  const committed = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
  if (serialise() === committed) return true;
  console.error("  FAIL  SPDX data is stale — run: npx tsx scripts/generate-spdx.ts");
  return false;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes("--check")) process.exit(checkSpdxData() ? 0 : 1);
  fs.writeFileSync(OUT_FILE, serialise());
  console.log(`  wrote ${path.relative(process.cwd(), OUT_FILE)}`);
}
